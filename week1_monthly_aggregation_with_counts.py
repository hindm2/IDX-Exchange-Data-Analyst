from pathlib import Path
import re
import pandas as pd

# 1. Set input and output folders.
data_dir = Path("/content/IDX_Analysis")
output_dir = Path("/content/combined_output")
output_dir.mkdir(parents=True, exist_ok=True)

csv_files = [
    p for p in data_dir.rglob("*.csv")
    if "__MACOSX" not in p.parts
    and not p.name.startswith("._")
]

report = [
    "WEEK 1 — MONTHLY AGGREGATION",
    "",
    "Listings: January 2024–June 2026",
    "Sold: January 2024–September 2026",
    "July–September 2026 Listings excluded: suspected 1,000-row download limit.",
    "January 2026 Listings included but flagged: previously counted 2,606 raw rows.",
    "Filter: PropertyType = Residential",
    "No PropertySubType filter or duplicate removal applied.",
    "File availability does not establish download completeness."
]

# 2. Verify required months before processing either dataset.
datasets = []

for label, prefix, end_month in [
    ("listings", "CRMLSListing", "202606"),
    ("sold", "CRMLSSold", "202609")
]:
    expected = pd.period_range(
        "2024-01",
        f"{end_month[:4]}-{end_month[4:]}",
        freq="M"
    ).strftime("%Y%m")

    by_month = {}

    for path in csv_files:
        match = re.fullmatch(
            rf"{prefix}(\d{{6}})(?:_filled)?\.csv",
            path.name,
            flags=re.IGNORECASE
        )

        if match and match.group(1) in expected:
            month = match.group(1)
            by_month.setdefault(month, []).append(path)

    missing = [month for month in expected if month not in by_month]
    duplicates = {
        month: [str(p) for p in paths]
        for month, paths in by_month.items()
        if len(paths) > 1
    }

    if missing or duplicates:
        raise ValueError(
            f"{label.upper()} file check failed.\n"
            f"Missing months: {missing}\n"
            f"Multiple files for the same month: {duplicates}"
        )

    paths = [by_month[month][0] for month in expected]
    datasets.append((label, end_month, paths))

    print(f"{label.upper()}: verified {len(paths)} monthly files")

# 3. Read, filter, combine, and save each dataset separately.
for label, end_month, paths in datasets:
    frames = []
    total_raw = 0
    total_residential = 0
    lines = [f"\n{label.upper()}"]

    for path in paths:
        df = pd.read_csv(path, low_memory=False)

        if "PropertyType" not in df.columns:
            raise ValueError(
                f"PropertyType column is missing in {path.name}"
            )

        raw_count = len(df)

        residential = df.loc[
            df["PropertyType"].eq("Residential")
        ].copy()

        residential_count = len(residential)
        total_raw += raw_count
        total_residential += residential_count
        frames.append(residential)

        lines.append(
            f"{path.name}: raw={raw_count:,}, "
            f"Residential={residential_count:,}"
        )

        del df, residential

    combined = pd.concat(frames, ignore_index=True)
    del frames

    if len(combined) != total_residential:
        raise ValueError("Unexpected row-count change during concatenation.")

    output_path = output_dir / (
        f"CRMLS_{label}_Residential_202401_{end_month}.csv"
    )
    combined.to_csv(output_path, index=False)

    lines.extend([
        f"Monthly files used: {len(paths)}",
        f"Total raw rows: {total_raw:,}",
        f"Total Residential rows: {len(combined):,}",
        f"Rows excluded by Residential filter: "
        f"{total_raw - len(combined):,}",
        f"Combined columns: {combined.shape[1]}",
        f"Saved: {output_path.name}"
    ])

    report.extend(lines)
    print("\n".join(lines))

    del combined

# 4. Save the detailed output report for GitHub.
report_path = output_dir / "week1_output.txt"
report_path.write_text("\n".join(report), encoding="utf-8")

print(f"\nReport saved: {report_path}")
print("Finished. Original monthly CSV files were not changed.")

